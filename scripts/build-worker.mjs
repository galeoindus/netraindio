/**
 * scripts/build-worker.mjs — flatten the harness into one ES module.
 * No bundler, no build dependency: our modules have unique top-level names,
 * so stripping imports/exports and concatenating in dependency order is exact.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const MODULES = [
  'src/lib/text.js',
  'src/lib/rss.js',
  'src/lib/bm25.js',
  'src/lib/summarize.js',
  'src/runtime/eventlog.js',
  'src/runtime/context.js',
  'src/runtime/skills.js',
  'src/tools/basic.js',
  'src/tools/web.js',
  'src/tools/news.js',
  'src/tools/notes.js',
  'src/tools/artifacts.js',
  'src/tools/index.js',
  'src/model/index.js',
  'src/runtime/subagents.js',
  'src/runtime/kernel.js',
  'src/server.js',
  'worker/index.js',
];

function strip(source, file) {
  return source
    .replace(/^\s*import\s+[\s\S]*?from\s+['"][^'"]+['"];?[ \t]*$/gm, '')
    .replace(/^\s*import\s+['"][^'"]+['"];?[ \t]*$/gm, '')
    .replace(/^export\s+(default\s+)?(const|let|var|function|async\s+function|class)\b/gm, '$2')
    .replace(/^export\s*\{[^}]*\};?[ \t]*$/gm, '')
    .trim()
    .replace(/^/, `// ─── ${file} ${'─'.repeat(Math.max(0, 56 - file.length))}\n`);
}

const parts = [];
for (const file of MODULES) parts.push(strip(await readFile(resolve(ROOT, file), 'utf8'), file));

const banner = `/**
 * netraindio — single-file Worker bundle. Generated by scripts/build-worker.mjs.
 * Source: https://github.com/galeoindus/netraindio
 */`;

const PUBLIC = [
  ['/index.html', 'public/index.html', 'text/html; charset=utf-8'],
  ['/styles.css', 'public/styles.css', 'text/css; charset=utf-8'],
  ['/app.js', 'public/app.js', 'text/javascript; charset=utf-8'],
  ['/icon.svg', 'public/icon.svg', 'image/svg+xml'],
  ['/manifest.webmanifest', 'public/manifest.webmanifest', 'application/manifest+json'],
];

const embedded = {};
for (const [urlPath, file, type] of PUBLIC) {
  embedded[urlPath] = { type, body: await readFile(resolve(ROOT, file), 'utf8') };
}

const assetsModule = `\n// ─── embedded assets ──────────────────────────────────────\nconst __ASSETS = ${JSON.stringify(embedded)};\n`;

const bundle = `${banner}\n\n${parts.join('\n\n')}\n${assetsModule}`;
await mkdir(resolve(ROOT, 'dist'), { recursive: true });
await writeFile(resolve(ROOT, 'dist/worker.js'), bundle, 'utf8');
console.log(`dist/worker.js — ${(bundle.length / 1024).toFixed(1)} KB, default export: ${/export\s+default/.test(bundle)}`);
